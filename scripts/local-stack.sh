#!/usr/bin/env bash
set -euo pipefail

LOCAL_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
LOCAL_DIR="${LOCAL_ROOT}/tmp/local-stack"
LOCAL_ENV="${LOCAL_DIR}/local.env"
LOCAL_HOST="${ORION_LOCAL_HOST:-127.0.0.1}"
POSTGRES_CONTAINER="orion-local-postgres"
POSTGRES_IMAGE="postgres:17.11-alpine3.23"
S3_CONTAINER="orion-local-s3"
S3_IMAGE="node:22-alpine"

if [[ ! "${LOCAL_HOST}" =~ ^[A-Za-z0-9.-]+$ ]]; then
  echo "ORION_LOCAL_HOST must be a hostname or IPv4 address" >&2
  exit 1
fi

docker_ready() { docker info >/dev/null 2>&1; }

ensure_docker() {
  if docker_ready; then return; fi
  if command -v colima >/dev/null 2>&1; then
    echo "Starting Colima..."
    colima start
  fi
  if ! docker_ready; then
    echo "Docker is unavailable. Start Docker Desktop or Colima and retry." >&2
    exit 1
  fi
}

container_exists() { docker container inspect "$1" >/dev/null 2>&1; }

start_postgres() {
  if container_exists "${POSTGRES_CONTAINER}"; then
    docker start "${POSTGRES_CONTAINER}" >/dev/null
  else
    docker volume create orion_local_pgdata >/dev/null
    docker run -d --name "${POSTGRES_CONTAINER}" \
      --label orion.local-stack=true \
      -p 127.0.0.1:55432:5432 \
      -e POSTGRES_USER=orion \
      -e POSTGRES_PASSWORD=orion_local_only \
      -e POSTGRES_DB=orion_local \
      -v orion_local_pgdata:/var/lib/postgresql/data \
      "${POSTGRES_IMAGE}" >/dev/null
  fi
}

start_s3() {
  local bind_host="127.0.0.1"
  if [[ "${LOCAL_HOST}" != "127.0.0.1" && "${LOCAL_HOST}" != "localhost" ]]; then
    bind_host="0.0.0.0"
  fi
  if container_exists "${S3_CONTAINER}" && [[ "$(cat "${LOCAL_DIR}/s3-host" 2>/dev/null || true)" != "${bind_host}" ]]; then
    docker rm -f "${S3_CONTAINER}" >/dev/null
  fi
  if container_exists "${S3_CONTAINER}"; then
    docker start "${S3_CONTAINER}" >/dev/null
  else
    mkdir -p "${LOCAL_DIR}/s3"
    docker run -d --name "${S3_CONTAINER}" \
      --label orion.local-stack=true \
      -p "${bind_host}:59000:59000" \
      -v "${LOCAL_ROOT}:/workspace" \
      -w /workspace \
      -e ORION_S3_DIRECTORY=/workspace/tmp/local-stack/s3 \
      -e ORION_S3_BIND_HOST=0.0.0.0 \
      "${S3_IMAGE}" node scripts/local-s3-server.mjs >/dev/null
  fi
  echo "${bind_host}" > "${LOCAL_DIR}/s3-host"
}

write_env() {
  local jwt_secret
  jwt_secret=""
  if [[ -f "${LOCAL_ENV}" ]]; then
    jwt_secret="$(sed -n 's/^JWT_SECRET=//p' "${LOCAL_ENV}" | head -n 1)"
  fi
  if [[ ! "${jwt_secret}" =~ ^[a-f0-9]{64}$ ]]; then
    jwt_secret="$(openssl rand -hex 32)"
  fi
  umask 077
  cat > "${LOCAL_ENV}" <<EOF
DATABASE_URL=postgresql://orion:orion_local_only@127.0.0.1:55432/orion_local?schema=public
DIRECT_URL=postgresql://orion:orion_local_only@127.0.0.1:55432/orion_local?schema=public
JWT_SECRET=${jwt_secret}
PORT=3001
API_PUBLIC_URL=http://${LOCAL_HOST}:3001
S3_USE_LOCAL_STORAGE=false
S3_BUCKET=orion-assets
S3_REGION=us-east-1
S3_ENDPOINT=http://${LOCAL_HOST}:59000
S3_FORCE_PATH_STYLE=true
S3_ACCESS_KEY_ID=S3RVER
S3_SECRET_ACCESS_KEY=S3RVER
CLOUDFRONT_MEDIA_DOMAIN=
CLOUDFRONT_KEY_PAIR_ID=
CLOUDFRONT_PRIVATE_KEY=
POP_LOG_QUEUE_URL=
CLOUDWATCH_METRICS=false
ORION_ENV=development
CORS_ORIGINS=http://localhost:3000
EOF
}

load_local_env() {
  if [[ ! -f "${LOCAL_ENV}" ]]; then
    echo "Local environment is missing. Run: npm run local:up" >&2
    exit 1
  fi
  set -a
  # This file is generated by write_env with validated host and fixed values.
  source "${LOCAL_ENV}"
  set +a
  export ORION_ENV_FILE="${LOCAL_ENV}"
}

configure_local_apk_verification() {
  local android_sdk build_tools debug_fingerprint
  android_sdk="${ANDROID_SDK_ROOT:-${ANDROID_HOME:-${HOME}/Library/Android/sdk}}"
  build_tools=""
  if [[ -d "${android_sdk}/build-tools" ]]; then
    build_tools="$(find "${android_sdk}/build-tools" -mindepth 1 -maxdepth 1 -type d -print | sort -V | tail -n 1)"
  fi
  if [[ -n "${build_tools}" && -x "${build_tools}/aapt" && -x "${build_tools}/apksigner" ]]; then
    export PATH="${build_tools}:${PATH}"
  fi

  if [[ -z "${PLAYER_RELEASE_CERT_SHA256:-}" && -f "${HOME}/.android/debug.keystore" ]]; then
    debug_fingerprint="$(keytool -list -v -alias androiddebugkey \
      -keystore "${HOME}/.android/debug.keystore" -storepass android -keypass android 2>/dev/null \
      | sed -n 's/^[[:space:]]*SHA256: //p' | head -n 1 | tr -d ':' | tr '[:upper:]' '[:lower:]')"
    if [[ "${debug_fingerprint}" =~ ^[a-f0-9]{64}$ ]]; then
      export PLAYER_RELEASE_CERT_SHA256="${debug_fingerprint}"
    fi
  fi
}

wait_for_services() {
  for _ in {1..60}; do
    if pg_isready -q -h 127.0.0.1 -p 55432 -U orion -d orion_local && \
       curl -sS -o /dev/null http://127.0.0.1:59000/; then
      return
    fi
    sleep 2
  done
  echo "Local services did not become ready. Check docker logs for the orion-local containers." >&2
  exit 1
}

cd "${LOCAL_ROOT}"
mkdir -p "${LOCAL_DIR}"

case "${1:-}" in
  up)
    ensure_docker
    start_postgres
    start_s3
    wait_for_services
    write_env
    load_local_env
    if [[ "${DATABASE_URL}" != 'postgresql://orion:orion_local_only@127.0.0.1:55432/orion_local?schema=public' ]]; then
      echo "Refusing to migrate a non-local database." >&2
      exit 1
    fi
    npm run prisma:generate
    npx prisma migrate deploy
    ORION_SEED_DEMO_DATA=true node --import tsx prisma/seed.ts
    node scripts/local-create-bucket.mjs
    echo "Local PostgreSQL and S3 are ready. Run npm run local:api and npm run local:web in separate terminals."
    ;;
  api)
    load_local_env
    configure_local_apk_verification
    npm run dev:api
    ;;
  web)
    load_local_env
    export NEXT_PUBLIC_API_URL="${API_PUBLIC_URL}"
    export PORT=3000
    npm run dev:web
    ;;
  status)
    ensure_docker
    docker ps --filter label=orion.local-stack=true --format 'table {{.Names}}\t{{.Status}}\t{{.Ports}}'
    ;;
  down)
    ensure_docker
    docker stop "${POSTGRES_CONTAINER}" "${S3_CONTAINER}" >/dev/null
    echo "Local services stopped; database and objects remain on disk."
    ;;
  *)
    echo "Usage: $0 {up|api|web|status|down}" >&2
    exit 2
    ;;
esac
